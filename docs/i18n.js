const supported = ['pt-BR', 'en', 'es'];
const requested = new URL(location.href).searchParams.get('lang');
let stored;
try { stored = localStorage.getItem('idlerite-language'); } catch {}
export const locale = [requested, stored, navigator.language?.split('-')[0]].find(code => supported.includes(code)) ?? 'pt-BR';
const column = supported.indexOf(locale);
const dictionary = new Map(translations.map(row => [row[0], row[column]]));

export function t(message, ...values) {
  return (dictionary.get(message) ?? String(message)).replace(/\{(\d+)\}/g, (_, index) => values[index] ?? '');
}

export function localize(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      return node.parentElement?.closest('script, style, textarea, select') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
    },
  });
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const value = node.textContent.trim();
    if (dictionary.has(value)) node.textContent = node.textContent.replace(value, t(value));
  }
  for (const item of root.querySelectorAll('[aria-label]')) item.setAttribute('aria-label', t(item.getAttribute('aria-label')));
}

document.documentElement.lang = locale;
document.title = t(document.title.replace(' · IdleRite Games', '')) + (document.title.endsWith(' · IdleRite Games') ? ' · IdleRite Games' : '');
const description = document.querySelector('meta[name="description"]');
if (description) description.content = t(description.content);
try { localStorage.setItem('idlerite-language', locale); } catch {}
localize(document.body);
for (const select of document.querySelectorAll('[data-language]')) {
  select.value = locale;
  select.addEventListener('change', () => {
    const url = new URL(location.href);
    url.searchParams.set('lang', select.value);
    location.replace(url);
  });
}
